type MessageKey = keyof typeof messages.it;

interface I18nContextType {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: MessageKey, vars?: Record<string, string>) => string;
}

const I18nContext = createContext<I18nContextType>(null!);

const LOCALE_STORAGE_KEY = "sdf_locale";

function readStoredLocale(): Locale {
  try {
    const s = localStorage.getItem(LOCALE_STORAGE_KEY);
    if (s === "en" || s === "it") return s;
  } catch {
    /* ignore */
  }
  return "it";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(readStoredLocale);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    try {
      localStorage.setItem(LOCALE_STORAGE_KEY, l);
    } catch {
      /* ignore */
    }
  }, []);

  const value = useMemo<I18nContextType>(() => {
    const t = (key: MessageKey, vars?: Record<string, string>) => {
      const template = messages[locale][key] ?? messages.it[key];
      if (!vars) return template;
      return Object.entries(vars).reduce((acc, [k, v]) => acc.replace(`{{${k}}}`, v), template);
    };
    return { locale, setLocale, t };
  }, [locale, setLocale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

/** Field label for self-metrics (uses `mf_<fieldKey>`). */
export function metricFieldKey(fieldKey: string): MessageKey {
  return `mf_${fieldKey}` as MessageKey;
}
